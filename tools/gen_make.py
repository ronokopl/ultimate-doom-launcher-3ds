"""Phase 4 generator: build/Sources + build/Modules + build/Build rows -> build/Makefile (devkitARM).

Run from the port root:  make -f build/Makefile -j16   (inside devkitPro's msys2 bash)
Link order = sheet order with zzautozend.cpp forced last (ZDoom autoseg markers bracket the registration sections).
"""
import os
from export import rows
from pk3 import ROOT

OUT = os.path.join(ROOT, 'build', 'Makefile')

def obj(unit):
    return 'build/obj/' + os.path.splitext(unit)[0] + '.o'

def main():
    B = {r['key']: r.get('value', '~') for r in rows('build', 'Build')}
    mods = {m['module']: m for m in rows('build', 'Modules')}
    units = [s for s in rows('build', 'Sources') if s.get('compile') == 'yes']
    units = [u for u in units if not u['unit'].endswith('zzautozend.cpp')] + \
            [u for u in units if u['unit'].endswith('zzautozend.cpp')]
    L = ['# GENERATED by tools/gen_make.py from sheets/build.xlsx (Sources, Modules, Build) -- edit the sheets',
         'DEVKITPRO ?= /opt/devkitpro', 'DEVKITARM ?= $(DEVKITPRO)/devkitARM', 'PREFIX := $(DEVKITARM)/bin/arm-none-eabi-',
         'CC := $(PREFIX)gcc', 'CXX := $(PREFIX)g++',
         'ARCH := %s' % B['arch_flags'],
         'BASE := -O2 -g -ffunction-sections -fno-strict-aliasing $(ARCH) -D__3DS__ -I$(DEVKITPRO)/libctru/include -I$(DEVKITPRO)/portlibs/3ds/include',
         'LDFLAGS := -specs=3dsx.specs -g $(ARCH) -Wl,-Map,build/doomlauncher3ds.map -L$(DEVKITPRO)/libctru/lib -L$(DEVKITPRO)/portlibs/3ds/lib %s' % B.get('ld_extra', ''),
         'LIBS := %s' % ' '.join('-l' + l for l in B['libs'].split()) + ' -lm',
         '']
    for name, m in mods.items():
        key = name.replace(':', '_').replace('-', '_').upper()
        inc = ' '.join('-I' + i for i in m.get('includes', '~').split() if i != '~')
        cf = m.get('cflags', '~'); cf = '' if cf == '~' else cf
        cx = m.get('cxxflags', '~'); cx = '' if cx == '~' else cx
        L += ['CFLAGS_%s := $(BASE) %s %s' % (key, cf, inc), 'CXXFLAGS_%s := $(CFLAGS_%s) %s' % (key, key, cx)]
    L += ['', 'OBJS := \\'] + ['\t%s \\' % obj(u['unit']) for u in units] + ['', 'all: build/doomlauncher3ds.3dsx build/doomlauncher3ds.cia', '']
    for u in units:
        key = u['module'].replace(':', '_').replace('-', '_').upper()
        extra = '' if u.get('flags', '~') == '~' else ' ' + u['flags']
        cpp = u['unit'].endswith(('.cpp', '.cc'))
        L += ['%s: %s' % (obj(u['unit']), u['unit']), '\t@mkdir -p $(@D)',
              '\t@echo CC $<',
              '\t@$(%s) $(%s_%s)%s -MMD -MP -c $< -o $@' % ('CXX' if cpp else 'CC', 'CXXFLAGS' if cpp else 'CFLAGS', key, extra)]
    L += ['', 'build/doomlauncher3ds.elf: $(OBJS)', '\t$(CXX) $(LDFLAGS) $(OBJS) $(LIBS) -o $@',
          '', 'build/doomlauncher3ds.smdh: platform/3ds/icon.png',
          '\t$(DEVKITPRO)/tools/bin/smdhtool --create "%s" "%s" "%s" $< $@' % (B['title'], B['target'], B['publisher']),
          '', 'build/doomlauncher3ds.3dsx: build/doomlauncher3ds.elf build/doomlauncher3ds.smdh',
          '\t$(DEVKITPRO)/tools/bin/3dsxtool $< $@ --smdh=build/doomlauncher3ds.smdh --romfs=build/romfs',
          '', '# CIA (tools/gen_cia.py makes build/cia/*): same ELF, romfs packed into the NCCH',
          'build/doomlauncher3ds.cia: build/doomlauncher3ds.elf build/cia/doomlauncher3ds.rsf build/cia/banner.bnr build/cia/icon.smdh $(wildcard build/romfs/*)',
          '\t"%s" -f cia -o $@ -elf $< -rsf build/cia/doomlauncher3ds.rsf -icon build/cia/icon.smdh -banner build/cia/banner.bnr'
          ' -exefslogo -target t -major %s -minor %s -micro %s' % ((B['makerom_exe'],) + tuple(str(B['cia_version']).split('.'))),
          '', 'objs: $(OBJS)', '.PHONY: all objs', '-include $(OBJS:.o=.d)', '']
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, 'w', newline='\n').write('\n'.join(L))
    print(OUT, len(units), 'units')

if __name__ == '__main__':
    main()
