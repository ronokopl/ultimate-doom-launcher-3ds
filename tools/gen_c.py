"""Phase 3 generator: platform.xlsx + build.xlsx rows -> gen/c/bd3ds_sheets.h (C glue for platform/3ds).

One table entry per row. ctru button masks are emitted as numbers (no 3ds.h needed in engine TUs);
ZDoom key codes are emitted symbolically (KEY_PAD_* from doomdef.h).
"""
import os, re
from export import rows
from pk3 import GEN

OUT = os.path.join(GEN, 'c', 'bd3ds_sheets.h')
CTRU = {'KEY_A': 0, 'KEY_B': 1, 'KEY_SELECT': 2, 'KEY_START': 3, 'KEY_DRIGHT': 4, 'KEY_DLEFT': 5, 'KEY_DUP': 6,
        'KEY_DDOWN': 7, 'KEY_R': 8, 'KEY_L': 9, 'KEY_X': 10, 'KEY_Y': 11, 'KEY_ZL': 14, 'KEY_ZR': 15}  # libctru hid.h BIT(n)

def cstr(v):
    return 'NULL' if v in (None, '~') else '"%s"' % str(v).replace('\\', '\\\\').replace('"', '\\"')

def ident(v):
    return re.sub(r'\W', '_', str(v)).upper()

def main():
    o = ['// GENERATED by tools/gen_c.py from sheets/platform.xlsx + sheets/build.xlsx -- edit the sheets', '#pragma once', '']
    B = {r['key']: r.get('value', '~') for r in rows('build', 'Build')}
    for k, v in B.items():
        if k == 'max_debris':
            o.append('#define BD3DS_MAX_DEBRIS %s  // %s' % ('-1' if v == 'unlimited' else v, v))
        elif re.fullmatch(r'-?\d+(\.\d+)?|0x[0-9A-Fa-f]+', str(v)):
            o.append('#define BD3DS_%s %s' % (ident(k), v))
        else:
            o.append('#define BD3DS_%s %s' % (ident(k), cstr(v)))
    o += ['', 'typedef struct { const char *name; int width, height; const char *scale; const char *gate; int is_default; const char *label; } bd3ds_video_mode_t;',
          'static const bd3ds_video_mode_t bd3ds_video_modes[] = {']
    V = rows('platform', 'Video')
    for r in V:
        o.append('\t{ %s, %s, %s, %s, %s, %d, %s },' % (cstr(r['mode']), r['width'], r['height'], cstr(r['scale']),
                                                       cstr(r['gate']), r.get('default') == 'yes', cstr(r['menu_label'])))
    o += ['};', '#define BD3DS_VIDEO_MODE_COUNT %d' % len(V),
          '#define BD3DS_VIDEO_MODE_DEFAULT %d' % next(i for i, r in enumerate(V) if r.get('default') == 'yes'), '']
    o += ['#ifndef BD3DS_NO_ENGINE_KEYS	// zdoom_key needs doomdef.h; the launcher runs before the engine and skips it',
          'typedef struct { const char *button; unsigned ctru_mask; int zdoom_key; const char *bind; int remappable; } bd3ds_button_t;',
          'static const bd3ds_button_t bd3ds_buttons[] = {']
    axes = []
    for r in rows('platform', 'Controls'):
        if r.get('analog') == 'yes':
            axes.append(r); continue
        mask = '(1u << %d) /* %s */' % (CTRU[r['ctru_key']], r['ctru_key'])
        o.append('\t{ %s, %s, %s, %s, %d },' % (cstr(r['button']), mask, r['zdoom_key'], cstr(r.get('command')),
                                                r.get('remappable') == 'yes'))
    o += ['};', '#define BD3DS_BUTTON_COUNT (sizeof(bd3ds_buttons) / sizeof(bd3ds_buttons[0]))', '#endif', '']
    o += ['typedef struct { const char *stick; const char *role; const char *axes; } bd3ds_axis_t;',
          'static const bd3ds_axis_t bd3ds_axes[] = {']
    o += ['\t{ %s, %s, %s },' % (cstr(r['button']), cstr(r['command']), cstr(r['zdoom_key'])) for r in axes]
    o += ['};', '#define BD3DS_AXIS_COUNT %d' % len(axes), '']
    BM = rows('platform', 'BottomModes')
    o += ['typedef struct { const char *mode; const char *label; int canvas; int backlight; } bd3ds_bottom_mode_t;',
          'static const bd3ds_bottom_mode_t bd3ds_bottom_modes[] = {']
    o += ['\t{ %s, %s, %d, %d },' % (cstr(r['mode']), cstr(r['menu_label']), r['canvas'] == 'yes', r['backlight'] == 'on')
          for r in sorted(BM, key=lambda r: int(r['value']))]
    o += ['};', '#define BD3DS_BOTTOM_MODE_COUNT %d' % len(BM), '']
    o += ['typedef struct { const char *element; const char *kind; const char *modes; int x, y, w, h; const char *command;',
          '\tconst char *label; const char *texture; const char *font_owned; const char *font_empty; } bd3ds_touch_t;',
          'static const bd3ds_touch_t bd3ds_bottom[] = {']
    BS = rows('platform', 'BottomScreen')
    o += ['\t{ %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s },' % (cstr(r['element']), cstr(r['kind']), cstr(r['modes']),
                                                r['x'], r['y'], r['w'], r['h'],
                                                cstr(r.get('command')), cstr(r.get('label')), cstr(r.get('texture')),
                                                cstr(r.get('font_owned')), cstr(r.get('font_empty'))) for r in BS]
    o += ['};', '#define BD3DS_BOTTOM_COUNT %d' % len(BS), '']
    o += ['typedef struct { const char *option; const char *menu; const char *cvar; const char *values; const char *dflt; } bd3ds_menu_t;',
          'static const bd3ds_menu_t bd3ds_menu[] = {']
    o += ['\t{ %s, %s, %s, %s, %s },' % (cstr(r['option']), cstr(r['menu']), cstr(r.get('cvar')), cstr(r['values']),
                                         cstr(r.get('default'))) for r in rows('platform', 'Menu')]
    o += ['};', '']
    # Menu defaults for the cvar definitions: option rows -> index of the default, slider rows -> the number
    for r in rows('platform', 'Menu'):
        if r.get('cvar', '~') == '~' or r.get('default', '~') == '~':
            continue
        if r.get('widget') == 'slider':
            o.append('#define BD3DS_DEFAULT_%s %sf' % (ident(r['cvar']), float(r['default'])))
        elif r.get('widget') == 'option' and r['default'] in r['values'].split('|'):	# not 'BottomModes sheet'
            o.append('#define BD3DS_DEFAULT_%s %d' % (ident(r['cvar']), r['values'].split('|').index(r['default'])))
    o += ['']
    # Menu row gyro_button: option index -> 3DS button mask (read directly, so it can share a bound button)
    PAD = {'D-Pad Up': 'DUP', 'D-Pad Down': 'DDOWN', 'D-Pad Left': 'DLEFT', 'D-Pad Right': 'DRIGHT'}
    for r in rows('platform', 'Menu'):
        if r.get('cvar') == 'gyro_button':
            masks = ['0 /* None */' if l == 'None' else '(1u << %d) /* %s */' % (CTRU['KEY_' + PAD.get(l, l)], l)
                     for l in r['values'].split('|')]
            o += ['static const unsigned bd3ds_gyro_buttons[] = { %s };' % ', '.join(masks),
                  '#define BD3DS_GYRO_BUTTON_COUNT %d' % len(masks), '']
    o += ['typedef struct { const char *element; const char *kind; const char *screen; int x, y, w, h; const char *label;',
          '\tconst char *action; unsigned key; } bd3ds_ui_t;', 'static const bd3ds_ui_t bd3ds_launcher[] = {']
    for r in rows('platform', 'Launcher'):
        key = '(1u << %d) /* %s */' % (CTRU['KEY_' + r['key']], r['key']) if r.get('key', '~') != '~' else '0'
        o.append('\t{ %s, %s, %s, %s, %s, %s, %s, %s, %s, %s },' % (cstr(r['element']), cstr(r['kind']), cstr(r['screen']),
                 r['x'], r['y'], r['w'], r['h'], cstr(r['label']), cstr(r.get('action')), key))
    o += ['};', '#define BD3DS_LAUNCHER_COUNT (sizeof(bd3ds_launcher) / sizeof(bd3ds_launcher[0]))', '']
    for r in rows('platform', 'ModCache'):	# rule names become feature switches for modcache_3ds.cpp
        o.append('#define BD3DS_MODCACHE_%s 1  // %s -> %s' % (ident(r['rule']), r['detect'], r['cache_entry']))
    o.append('')
    for r in rows('platform', 'Filesystem'):
        o.append('#define BD3DS_PATH_%s %s' % (ident(r['role']), cstr(r['path'])))
    o.append('')
    for r in rows('platform', 'Audio'):
        o.append('#define BD3DS_AUDIO_%s %s  // %s' % (ident(r['item']), cstr(r['target']), r.get('where', '')))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, 'w', newline='\n').write('\n'.join(o) + '\n')
    print(OUT, len(o), 'lines')

if __name__ == '__main__':
    main()
